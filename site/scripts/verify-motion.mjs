const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto('http://127.0.0.1:4173');
await page.waitForSelector('.canvas-ready');
const box=await page.locator('.harness-scene').boundingBox();
const neutral=await page.locator('.scene-canvas').evaluate(n=>n.toDataURL());
await page.mouse.move(box.x+box.width*.18,box.y+box.height*.25);
await page.waitForFunction(()=>Math.abs(parseFloat(document.querySelector('[data-point="agent"]').style.getPropertyValue('--offset-x')))>1);
const moved=await page.locator('.scene-canvas').evaluate(n=>n.toDataURL());assert.notEqual(neutral,moved);
console.log('cursor response',await page.locator('[data-point="agent"]').getAttribute('style'));
await page.mouse.move(5,5);
await page.waitForFunction(()=>Math.abs(parseFloat(document.querySelector('[data-point="agent"]').style.getPropertyValue('--offset-x')))<.1);
console.log('pointer exit settled');
const app=page.locator('.app-figure');await app.scrollIntoViewIfNeeded();
await page.waitForFunction(()=>document.querySelector('.app-figure').dataset.revealed==='true');
assert(await app.evaluate(n=>n.getAnimations().length)>0);
await page.evaluate(()=>Promise.allSettled(document.getAnimations().map(a=>a.finished)));
assert.equal(await app.evaluate(n=>getComputedStyle(n).transform),'none');
await page.locator('.command-panel').scrollIntoViewIfNeeded();
await page.waitForFunction(()=>document.querySelector('.command-panel').dataset.revealed==='true');
await page.emulateMedia({reducedMotion:'reduce'});
await page.waitForFunction(()=>document.getAnimations().length===0);
assert.equal(await page.evaluate(()=>document.getAnimations().length),0);
await page.locator('.harness-scene').scrollIntoViewIfNeeded();
await page.mouse.move(box.x+box.width*.8,box.y+box.height*.5);
assert.equal(await page.locator('[data-point="agent"]').evaluate(n=>parseFloat(n.style.getPropertyValue('--offset-x'))),0);
console.log('scroll entrance, resting state and reduced motion passed');
await page.emulateMedia({reducedMotion:'no-preference'});
await page.goto('http://127.0.0.1:4173');
await page.locator('[data-node="docs"]').focus();await page.keyboard.press('Enter');
assert.equal(await page.locator('#node-title').textContent(),'스킬 · docs skill');
await page.locator('[data-node="docs"]').focus();await page.keyboard.press('Enter');
assert.equal(await page.locator('#node-title').textContent(),'적어둔 연결과 실제 쓴 연결');
assert.deepEqual(errors,[]);
await page.close();
const touch=await browser.newContext({isMobile:true,hasTouch:true,viewport:{width:375,height:812}});
const mobile=await touch.newPage();await mobile.goto('http://127.0.0.1:4173');
assert.equal(await mobile.evaluate(()=>matchMedia('(pointer: fine)').matches),false);
await mobile.locator('[data-node="mcp"]').tap();assert.equal(await mobile.locator('#node-title').textContent(),'MCP · filesystem');
console.log('keyboard and touch passed');await touch.close();await browser.close();
